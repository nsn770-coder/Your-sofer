// ── Calculate retail price ────────────────────────────────
function calculatePrice(supplierPrice, category) {
  // כיפות: multiply by 3
  if (category === 'כיפות') {
    return Math.round(supplierPrice * 3);
  }

  // All other categories: multiply by 2.18
  return Math.round(supplierPrice * 2.18);
}

// ── main ──────────────────────────────────────────────────
async function main() {
  const args = process.argv.slice(2);
  const testMode = args.includes('--test');

  // Fetch existing SKUs
  const existingSnap = await db.collection('products').select('sku').get();
  const existingSkus = new Set();
  existingSnap.forEach(d => { if (d.data().sku) existingSkus.add(d.data().sku); });

  console.log(`\n${testMode ? '🧪 TEST MODE' : '🚀 UPLOADING'} — ${PRODUCTS_DATA.length} products from manual list`);
  console.log(`Found ${existingSkus.size} existing products in Firestore.\n`);

  const subset = testMode ? PRODUCTS_DATA.slice(0, 5) : PRODUCTS_DATA;
  let created = 0, skipped = 0, failed = 0;

  for (let i = 0; i < subset.length; i++) {
    const [sku, name, category, supplierPrice, status] = subset[i];

    if (existingSkus.has(sku)) {
      console.log(`[${i + 1}/${subset.length}] ⏭  SKIP — already exists: ${sku}`);
      skipped++;
      continue;
    }

    const retailPrice = calculatePrice(supplierPrice, category);
    const imageUrl = skuToImages[sku] || '';
    const doc = {
      name,
      sku,
      imgUrl: imageUrl,
      images: imageUrl ? [imageUrl] : [],
      cat: category,
      category,
      subCategory: category,
      price: retailPrice,
      soferBasePrice: supplierPrice,
      source: 'israel-judaica',
      sourceUrl: `https://www.israel-judaica.com/index.php?option=com_art&view=product&sku=${sku}&lang=he`,
      status: 'active',
      available: true,  // Available now with "coming soon" badge
      hidden: false,
      outOfStock: false,
      priority: 50,
      isBestSeller: false,
      badge: 'מגיע בקרוב',
      createdAt: new Date().toISOString(),
    };

    if (testMode) {
      console.log(`[${i + 1}/5] ✅ WOULD CREATE: ${sku} — ₪${supplierPrice}→₪${retailPrice} [${category}]`);
      created++;
      continue;
    }

    try {
      const ref = await db.collection('products').add(doc);
      console.log(`[${i + 1}/${PRODUCTS_DATA.length}] ✅ ${sku} — ₪${retailPrice} [${category}]`);
      created++;
    } catch (e) {
      console.error(`[${i + 1}/${PRODUCTS_DATA.length}] ❌ ${sku}: ${e.message}`);
      failed++;
    }
  }

  console.log(`\n${'─'.repeat(50)}`);
  if (testMode) {
    console.log(`✅ Test: ${created} | ⏭ Skipped: ${skipped}`);
  } else {
    console.log(`✅ Created: ${created} | ⏭ Skipped: ${skipped} | ❌ Failed: ${failed}`);
  }
  process.exit(0);
}

main().catch(e => { console.error('Fatal:', e); process.exit(1); });
